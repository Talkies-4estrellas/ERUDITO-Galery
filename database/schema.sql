-- ── Artistas ─────────────────────────────────────────────────
create table if not exists artistas (
  id_artista      bigint primary key generated by default as identity,
  nombre          text    not null,
  biografia       text,
  email           text    unique,            -- nullable: marcas/artistas históricos sin email
  telefono        text,
  redes_sociales  jsonb,                     -- { ig, fb, tw, web }
  foto_perfil     text,
  vida            text,                      -- "1890 – 1960"
  origen          text,
  especialidad    text,
  fecha_registro  timestamptz default now()
);

alter table artistas enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='artistas' and policyname='Lectura pública de artistas') then
    execute 'create policy "Lectura pública de artistas" on artistas for select using (true)';
  end if;
end $$;


-- ── Obras ─────────────────────────────────────────────────────
create table if not exists obras (
  id_obra           bigint primary key generated by default as identity,
  id_artista        bigint references artistas(id_artista) on delete set null,
  titulo            text    not null,
  descripcion       text,
  precio            numeric(10,2),
  stock             int     default 1,
  categoria         text,
  tecnica           text,
  dimensiones       text,
  imagen_principal  text,
  perspectivas      jsonb,                   -- ["url1", "url2"]
  imagenes          jsonb,
  anio              text,
  movimiento        text,
  tamano            text check (tamano in ('Pequeño','Mediano','Grande')),
  color             text check (color  in ('Cálido','Frío','Neutro')),
  tipo              text check (tipo   in ('Físico','JPG Certificado','Impresión Oficial','Edición limitada')),
  estrellas         int  check (estrellas between 1 and 5) default 5,
  grafica_valor     jsonb,                   -- [{ "mes":"Ene","valor":36000 }] × 12
  grafica_interes   jsonb,                   -- [42,58,35,...] × 7 puntos
  certificaciones   jsonb,                   -- ["Verificada autenticidad…"]
  -- columnas añadidas en producción
  vistas            int     default 0,       -- contador de visitas (RPC incrementar_vistas)
  estado            text    default 'pendiente'
                      check (estado in ('pendiente','aprobada','rechazada')),
  artista_email     text,                    -- email artista de plataforma (tabla usuarios)
  empresa_email     text,                    -- email galería/empresa (tabla usuarios)
  nombre_artista    text,                    -- artista representado por empresa
  fecha_creacion    timestamptz default now()
);

alter table obras enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='obras' and policyname='Lectura pública de obras') then
    execute 'create policy "Lectura pública de obras" on obras for select using (true)';
  end if;
end $$;


