-- ── Ventas (Mercado Pago) ─────────────────────────────────────
create table if not exists ventas (
  id                  bigint primary key generated always as identity,
  obra_id             bigint references obras(id_obra) on delete set null,
  titulo              text,
  precio              numeric(10,2),
  tipo                text,
  comprador_nombre    text,
  comprador_email     text,
  comprador_telefono  text,
  mensaje             text,
  mp_preference_id    text,                -- ID de preferencia Mercado Pago
  mp_payment_id       text,                -- ID de pago (llega por webhook)
  estado              text default 'pendiente'
                        check (estado in ('pendiente','en_proceso','pagado','cancelado')),
  created_at          timestamptz default now()
);

-- Acceso solo vía service role (webhook + admin)


-- ── Reseñas ───────────────────────────────────────────────────
create table if not exists resenas (
  id         bigint primary key generated always as identity,
  obra_id    bigint references obras(id_obra) on delete cascade,
  nombre     text   not null,
  estrellas  int    not null check (estrellas between 1 and 5),
  comentario text   not null,
  email      text,                          -- nullable; usado para anti-duplicado
  created_at timestamptz default now(),
  unique (obra_id, email)                   -- un email = una reseña por obra
);

