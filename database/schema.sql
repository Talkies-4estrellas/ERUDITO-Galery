-- ── Usuarios (auth custom sin Supabase Auth) ──────────────────
--    Artistas y empresas aprobados vía solicitudes.
--    Compradores se registran directo.
--    Productores asignados manualmente.
create table if not exists usuarios (
  email        text primary key,
  clave        text not null,               -- ⚠ texto plano — pendiente bcrypt
  rol          text not null
                 check (rol in ('artista','comprador','empresa','productor','admin')),
  nombre       text    default '',
  bio          text    default '',
  especialidad text    default '',
  pais         text    default '',
  slug         text    unique,              -- solo empresas: "mi-galeria"
  avatar_url   text    default '',
  banner_url   text    default '',
  created_at   timestamptz default now()
);

alter table usuarios enable row level security;
do $$ begin
  -- Lectura pública: login desde el cliente usa anon key
  if not exists (select 1 from pg_policies where tablename='usuarios' and policyname='Lectura pública de usuarios') then
    execute 'create policy "Lectura pública de usuarios" on usuarios for select using (true)';
  end if;
  -- Inserción pública: registro de compradores
  if not exists (select 1 from pg_policies where tablename='usuarios' and policyname='Inserción pública de usuarios') then
    execute 'create policy "Inserción pública de usuarios" on usuarios for insert with check (true)';
  end if;
end $$;


-- ── Perfiles (Supabase Auth) ──────────────────────────────────
--    Ligados a auth.users. Artistas/empresas/compradores/productores
--    con cuenta GoTrue también tienen fila aquí.
create table if not exists perfiles (
  id           uuid references auth.users(id) on delete cascade primary key,
  rol          text not null
                 check (rol in ('artista','comprador','empresa','admin','productor')),
  nombre       text    default '',
  bio          text    default '',
  especialidad text    default '',
  pais         text    default '',
  slug         text    unique,
  avatar_url   text    default '',
  banner_url   text    default '',          -- portada/banner del perfil
  creado_at    timestamptz default now()
);

alter table perfiles enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='perfiles' and policyname='Ver propio perfil') then
    execute 'create policy "Ver propio perfil" on perfiles for select using (auth.uid() = id)';
  end if;
  if not exists (select 1 from pg_policies where tablename='perfiles' and policyname='Crear propio perfil') then
    execute 'create policy "Crear propio perfil" on perfiles for insert with check (auth.uid() = id)';
  end if;
  if not exists (select 1 from pg_policies where tablename='perfiles' and policyname='Editar propio perfil') then
    execute 'create policy "Editar propio perfil" on perfiles for update using (auth.uid() = id)';
  end if;
end $$;


-- ── Solicitudes de acceso ─────────────────────────────────────
--    Artistas y empresas que solicitan unirse.
--    El admin las aprueba → se mueven a usuarios.
create table if not exists solicitudes (
  id           bigint primary key generated always as identity,
  email        text   not null,
  clave        text   not null,
  rol          text   not null check (rol in ('artista','empresa')),
  nombre       text   default '',
  bio          text   default '',
  especialidad text   default '',
  pais         text   default '',
  motivacion   text   default '',
  estado       text   default 'pendiente'
                 check (estado in ('pendiente','aprobado','rechazado')),
  motivo       text,                        -- motivo de rechazo escrito por admin (nullable)
  revisado_at  timestamptz,
  created_at   timestamptz default now()
);

alter table solicitudes enable row level security;
do $$ begin
  -- Cualquiera puede crear una solicitud
  if not exists (select 1 from pg_policies where tablename='solicitudes' and policyname='Inserción pública de solicitudes') then
    execute 'create policy "Inserción pública de solicitudes" on solicitudes for insert with check (true)';
  end if;
  -- Lectura solo vía service role (admin panel usa getServerSupabase())
end $$;

